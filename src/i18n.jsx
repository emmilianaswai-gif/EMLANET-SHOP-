let _langListeners = [];

export function subscribeLanguage(cb) {
  _langListeners.push(cb);
  return () => { _langListeners = _langListeners.filter((fn) => fn !== cb); };
}

const LanguageContext = createContext({ lang: "en", setLang: () => {} });

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(getLanguage);

  useEffect(() => {
    const unsub = subscribeLanguage((newLang) => setLangState(newLang));
    return unsub;
  }, []);

  const setLang = useCallback((code) => {
    setLanguage(code);
    _langListeners.forEach((fn) => fn(code));
  }, []);

  return (
    <LanguageContext.Provider value={{ lang, setLang }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}

