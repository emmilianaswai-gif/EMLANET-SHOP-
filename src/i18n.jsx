export function getLanguage() {
  return localStorage.getItem("shop_language") || "en";
}

export function setLanguage(lang) {
  localStorage.setItem("shop_language", lang);
  applyDir(lang);
}

export function getDir(lang) {
  return RTL_LANGS.includes(lang) ? "rtl" : "ltr";
}

const RTL_LANGS = ["ar"];

function applyDir(lang) {
  // PDF export and text alignment use the RTL flag; the DOM is not available
  // in React Native so there is nothing to mutate here.
  if (typeof document !== "undefined" && document?.documentElement?.setAttribute) {
    document.documentElement.setAttribute("dir", getDir(lang) === "rtl" ? "rtl" : "ltr");
  }
}

export function t(key, params) {
  const lang = getLanguage();
  let str = translations[lang]?.[key] || translations.en[key] || key;
  if (params && typeof params === "object") {
    Object.keys(params).forEach((k) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(params[k]));
    });
  }
  return str;
}

